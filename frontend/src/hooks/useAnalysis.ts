import { useCallback, useRef, useState } from "react";
import type { PipelineState } from "../types";
import {
  analyzeAudioStream,
  analyzeImageStream,
  analyzeTextStream,
  streamSSE,
} from "../lib/api";

const INITIAL: PipelineState = {
  liveStatus: "ready",
  statusText: "Awaiting Image Evidence",
  scanning: false,
  router: { status: "idle", text: "Awaiting Signal..." },
  vit: { status: "idle", text: "Feature Extraction" },
  llm: { status: "idle", text: "Clinical Output" },
  routeLine1Active: false,
  routeLine2Active: false,
  progress: 0,
  progressColor: "blue",
  progressPulse: false,
  progressLabel: "Idle",
  progressText: "Please upload an image to begin pipeline.",
  confidence: "---",
  confidenceTier: null,
  inferenceTime: "---",
  domain: "---",
  reportVisible: false,
  report: "",
  transcription: null,
};

function elapsedSince(start: number): string {
  return ((Date.now() - start) / 1000).toFixed(2);
}

export function useAnalysis() {
  const [state, setState] = useState<PipelineState>(INITIAL);
  const runId = useRef(0);

  const patch = useCallback((p: Partial<PipelineState>) => {
    setState((prev) => ({ ...prev, ...p }));
  }, []);

  const handleError = useCallback(
    (err: unknown) => {
      const message = err instanceof Error ? err.message : "Failed to process.";
      patch({
        scanning: false,
        statusText: "Analysis Interrupted",
        progressLabel: "Error",
        progressText: message,
        progress: 10,
        progressColor: "red",
        progressPulse: false,
      });
    },
    [patch]
  );

  // ---- Image ----
  const analyzeImage = useCallback(
    async (file: File) => {
      const id = ++runId.current;
      patch({
        reportVisible: false,
        report: "",
        transcription: null,
        scanning: true,
        liveStatus: "scanning",
        statusText: "Analyzing Clinical Image...",
        router: { status: "active", text: "Routing inference...", spinning: true },
        vit: { status: "idle", text: "Feature Extraction" },
        llm: { status: "idle", text: "Clinical Output" },
        routeLine1Active: false,
        routeLine2Active: false,
        progress: 30,
        progressColor: "blue",
        progressPulse: false,
        progressLabel: "MobileNet Fast Routing",
        progressText: "Classifying image domain (skin, eye, dental)...",
        confidence: "---",
        confidenceTier: null,
        inferenceTime: "---",
        domain: "---",
      });

      // Visual-only intermediate step (router done -> ViT active)
      window.setTimeout(() => {
        if (runId.current !== id) return;
        setState((prev) => ({
          ...prev,
          router: { ...prev.router, status: "done", spinning: false },
          routeLine1Active: true,
          vit: { status: "active", text: "Deep Feature Extraction...", spinning: true },
          progress: 60,
          progressLabel: "Vision Transformer Active",
          progressText: "Identifying specific pathology from visual features...",
        }));
      }, 800);

      const start = Date.now();
      try {
        const res = await analyzeImageStream(file);
        let report = "";
        for await (const ev of streamSSE(res)) {
          if (runId.current !== id) return;
          if (ev.type === "classification") {
            const domain = ev.routing.domain;
            const disease = ev.classification.disease;
            const conf = ev.classification.confidence;
            const tier = conf > 80 ? "high" : conf > 50 ? "moderate" : "low";
            patch({
              scanning: false,
              statusText: disease.replace(/_/g, " ").toUpperCase(),
              liveStatus: "complete",
              router: { status: "done", text: `${domain.toUpperCase()} Domain` },
              vit: { status: "done", text: disease, accent: "blue" },
              routeLine2Active: true,
              llm: {
                status: "active",
                text: "Generating Report...",
                accent: "emerald",
                emerald: true,
                spinning: true,
              },
              progress: 80,
              progressColor: "blue",
              progressLabel: "LLM Synthesis...",
              progressText: "Clinical report is being generated by Gemma.",
              confidence: `${conf.toFixed(2)}%`,
              confidenceTier: tier,
              domain,
              reportVisible: true,
            });
          } else if (ev.type === "token") {
            report += ev.content;
            patch({ report, inferenceTime: `${elapsedSince(start)}s` });
          } else if (ev.type === "done") {
            patch({
              llm: {
                status: "done",
                text: "Report Generated",
                accent: "emerald",
                emerald: true,
              },
              progress: 100,
              progressColor: "emerald",
              progressLabel: "LLM Synthesis Complete",
              progressText: "Clinical report successfully generated by Gemma.",
              inferenceTime: `${elapsedSince(start)}s`,
            });
          }
        }
      } catch (err) {
        if (runId.current === id) handleError(err);
      }
    },
    [patch, handleError]
  );

  // ---- Shared reset for text/voice ----
  const resetForAnalysis = useCallback(
    (type: "Text" | "Audio") => {
      patch({
        reportVisible: false,
        report: "",
        transcription: null,
        scanning: false,
        router: { status: "idle", text: "Skipped (Direct to LLM)" },
        vit: { status: "idle", text: "Skipped (Text/Audio)" },
        llm: { status: "idle", text: "Generating Report...", spinning: true },
        routeLine1Active: false,
        routeLine2Active: false,
        progress: 50,
        progressColor: "blue",
        progressPulse: true,
        progressLabel: `Analyzing ${type}`,
        progressText: "Reasoning engine is processing. This takes ~15-30s. Please wait...",
        confidence: "---",
        confidenceTier: null,
        inferenceTime: "---",
        domain: "---",
      });
    },
    [patch]
  );

  const finish = useCallback(
    (elapsed: string, report: string, transcription: string | null) => {
      patch({
        router: { status: "idle", text: "Bypassed" },
        vit: { status: "idle", text: "Bypassed" },
        llm: { status: "done", text: "Report Generated", accent: "emerald", emerald: true },
        progress: 100,
        progressColor: "emerald",
        progressPulse: false,
        progressLabel: "Analysis Complete",
        progressText: `Report generated in ${elapsed}s.`,
        confidence: "N/A",
        confidenceTier: null,
        inferenceTime: `${elapsed}s`,
        domain: "Symptom Processing",
        reportVisible: true,
        report,
        transcription,
      });
    },
    [patch]
  );

  // ---- Text ----
  const analyzeText = useCallback(
    async (symptoms: string) => {
      const id = ++runId.current;
      resetForAnalysis("Text");
      const start = Date.now();
      try {
        const res = await analyzeTextStream(symptoms);
        let report = "";
        for await (const ev of streamSSE(res)) {
          if (runId.current !== id) return;
          if (ev.type === "text_start") {
            patch({
              reportVisible: true,
              progress: 80,
              progressLabel: "LLM Synthesis...",
              progressText: "Clinical report is being generated by Gemma.",
            });
          } else if (ev.type === "token") {
            report += ev.content;
            patch({ report, inferenceTime: `${elapsedSince(start)}s` });
          } else if (ev.type === "done") {
            finish(elapsedSince(start), report, null);
          }
        }
      } catch (err) {
        if (runId.current === id) handleError(err);
      }
    },
    [patch, resetForAnalysis, finish, handleError]
  );

  // ---- Voice ----
  const analyzeAudio = useCallback(
    async (audio: Blob) => {
      const id = ++runId.current;
      resetForAnalysis("Audio");
      const start = Date.now();
      let transcription = "";
      try {
        const res = await analyzeAudioStream(audio);
        let report = "";
        for await (const ev of streamSSE(res)) {
          if (runId.current !== id) return;
          if (ev.type === "error") {
            throw new Error(ev.message);
          } else if (ev.type === "audio_start") {
            transcription = ev.transcription;
            patch({
              transcription,
              reportVisible: true,
              progress: 80,
              progressLabel: "LLM Synthesis...",
              progressText: "Clinical report is being generated by Gemma.",
            });
          } else if (ev.type === "token") {
            report += ev.content;
            patch({ report, inferenceTime: `${elapsedSince(start)}s` });
          } else if (ev.type === "done") {
            finish(elapsedSince(start), report, transcription);
          }
        }
      } catch (err) {
        if (runId.current === id) handleError(err);
      }
    },
    [patch, resetForAnalysis, finish, handleError]
  );

  return { state, analyzeImage, analyzeText, analyzeAudio };
}
